// cp437 short-name decoding (matches bytes([b]).decode("cp437")) and LFN UTF-16LE
// code-unit assembly (matches per-unit chr() + join, lone surrogates pass through).
const HIGH = ['Ç', 'ü', 'é', 'â', 'ä', 'à', 'å', 'ç', 'ê', 'ë', 'è', 'ï', 'î', 'ì', 'Ä', 'Å', 'É', 'æ', 'Æ', 'ô', 'ö', 'ò', 'û', 'ù', 'ÿ', 'Ö', 'Ü', '¢', '£', '¥', '₧', 'ƒ', 'á', 'í', 'ó', 'ú', 'ñ', 'Ñ', 'ª', 'º', '¿', '⌐', '¬', '½', '¼', '¡', '«', '»', '░', '▒', '▓', '│', '┤', '╡', '╢', '╖', '╕', '╣', '║', '╗', '╝', '╜', '╛', '┐', '└', '┴', '┬', '├', '─', '┼', '╞', '╟', '╚', '╔', '╩', '╦', '╠', '═', '╬', '╧', '╨', '╤', '╥', '╙', '╘', '╒', '╓', '╫', '╪', '┘', '┌', '█', '▄', '▌', '▐', '▀', 'α', 'ß', 'Γ', 'π', 'Σ', 'σ', 'µ', 'τ', 'Φ', 'Θ', 'Ω', 'δ', '∞', 'φ', 'ε', '∩', '≡', '±', '≥', '≤', '⌠', '⌡', '÷', '≈', '°', '∙', '·', '√', 'ⁿ', '²', '■', ' '];

export function cp437Decode(bytes) {
  let s = "";
  for (const b of bytes) {
    if (b < 0 || b > 0xff) throw new RangeError(`cp437 byte out of range: ${b}`);
    s += b < 0x80 ? String.fromCharCode(b) : HIGH[b - 0x80];
  }
  return s;
}

export function lfnName(units) {
  let s = "";
  for (const u of units) s += String.fromCharCode(u);
  return s;
}
